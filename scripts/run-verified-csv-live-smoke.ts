import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import sharp from "sharp";
import { createAdminSessionValue, ADMIN_SESSION_COOKIE_NAME } from "../src/lib/admin-session";
async function main() {
 const origin = process.env.VERIFIED_CSV_SMOKE_ORIGIN || "http://127.0.0.1:3002";
 const cookie = ADMIN_SESSION_COOKIE_NAME+"="+await createAdminSessionValue();
 const auth={Cookie:cookie, Authorization:"Bearer kingmaker-local-admin-cookie"};
 const template=await fetch(origin+"/api/kingmaker/verified-csv?template=1");
 assert.equal(template.status,200);
 const header=(await template.text()).trim();
 const page=await fetch(origin+"/kingmaker/verified-csv",{headers:auth});
 assert.equal(page.status,200);
 assert.ok((await page.text()).includes("Verified CSV Intake"));
 const unauthorized=await fetch(origin+"/api/kingmaker/verified-csv",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({action:"commit",token:"not-a-real-token"})});
 assert.equal(unauthorized.status,401);
 const photo=async(color:string)=>new Blob([new Uint8Array(await sharp({create:{width:40,height:60,channels:3,background:color}}).png().toBuffer())],{type:"image/png"});
 const front=await photo("red"),back=await photo("blue");
 const fields:Record<string,string>={schema_version:"1",external_id:"isolated-preview-only-"+Date.now(),year:"2025",manufacturer:"Fixture",product:"TEST ONLY",card_number:"007",player:"Preview fixture - never imported",sport:"Basketball",parallel:"Base",autograph:"false",memorabilia:"false",patch:"false",rookie:"false",condition:"Near Mint or Better",front_image:"front.png",back_image:"back.png"};
 const row=header.split(",").map(k=>fields[k]||"").join(",");
 const form=new FormData();
 form.set("csv_file",new Blob([header+"\n"+row+"\n"],{type:"text/csv"}),"cards.csv");
 form.append("images",front,"front.png");form.append("images",back,"back.png");
 form.set("owner_id","untrusted-owner-must-be-replaced");
 const previewResponse=await fetch(origin+"/api/kingmaker/verified-csv",{method:"POST",headers:auth,body:form,signal:AbortSignal.timeout(90_000)});
 const preview=await previewResponse.json();
 assert.equal(previewResponse.status,200,JSON.stringify(preview));
 assert.equal(preview.canImport,true);
 assert.deepEqual(preview.counts,{ready:1,duplicate:0,error:0,total:1});
 assert.equal(preview.rows[0].identity.card_number,"007");
 const imageResponse=await fetch(origin+preview.rows[0].front.url,{headers:auth});
 assert.equal(imageResponse.status,200);
 assert.ok((await imageResponse.arrayBuffer()).byteLength>0);
 const unauthImage=await fetch(origin+preview.rows[0].front.url);
 assert.equal(unauthImage.status,401);
 const invalid=new FormData();
 invalid.set("csv_file",new Blob([header+"\n"+row.replace(",2025,",",bad-year,")+"\n"],{type:"text/csv"}),"invalid.csv");
 invalid.append("images",front,"front.png");invalid.append("images",back,"back.png");
 const invalidResponse=await fetch(origin+"/api/kingmaker/verified-csv",{method:"POST",headers:auth,body:invalid});
 const errors=await invalidResponse.json();
 assert.equal(invalidResponse.status,200);
 assert.equal(errors.counts.error,1);
 assert.equal(errors.canImport,false);
 const rejectedCommit=await fetch(origin+"/api/kingmaker/verified-csv",{method:"POST",headers:{...auth,"Content-Type":"application/json"},body:JSON.stringify({action:"commit",token:errors.token})});
 assert.equal(rejectedCommit.status,422);
 const result={ok:true,origin,template:header,authenticatedPage:200,anonymousImport:401,validPreview:{rows:1,ready:1,errors:0},mappedFrontImage:200,anonymousPreviewImage:401,invalidPreview:{errors:1,canImport:false},invalidCommit:422,productionCardsImported:0,productionLessonsCreated:0,completedAt:new Date().toISOString()};
 writeFileSync(".codex-run/verified-csv-live-smoke.json",JSON.stringify(result,null,2));
 console.log(JSON.stringify(result,null,2));
}
main().catch(error=>{console.error(error instanceof Error?error.message:String(error));process.exit(1)});
